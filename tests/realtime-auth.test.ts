import test from "node:test";
import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { authFixture } from "./auth-fixture";
import { getAuth } from "../src/lib/auth";
import { POST } from "../src/app/api/realtime/route";
import { issueRealtimeGrant, verifyRealtimeGrant } from "../src/lib/realtime-auth";

test("Realtime : session exigée, renouvellement sans lecture DB, jeton limité et falsification refusée", async t => {
  const fixture = await authFixture();
  process.env.DATABASE_URL = "postgresql://test:test@127.0.0.1:1/neondb";
  process.env.NEON_REALTIME_URL = "https://realtime.example.test/";
  process.env.NEON_REALTIME_SECRET = "nrt_live_1" + randomBytes(32).toString("base64url");
  const request = (payload: unknown, cookie?: string, origin = "http://127.0.0.1:3001") => new Request("http://127.0.0.1:3001/api/realtime", { method: "POST", headers: { "content-type": "application/json", origin, ...(cookie ? { cookie } : {}) }, body: JSON.stringify(payload) });
  assert.equal((await POST(request({}))).status, 401);
  assert.equal((await POST(request({}, fixture.cookie, "https://foreign.example.test"))).status, 403);
  const first = await POST(request({}, fixture.cookie));
  assert.equal(first.status, 200);
  assert.match(first.headers.get("cache-control")!, /no-store/);
  const data = await first.json();
  assert.ok(data.sealedQuery.capability);
  assert.equal(JSON.stringify(data).includes(process.env.NEON_REALTIME_SECRET), false);
  assert.equal(JSON.stringify(data).includes("SELECT"), false);
  const identity = verifyRealtimeGrant(data.grant);
  assert.equal(identity.userId, fixture.userId);
  const auth = await getAuth();
  t.mock.method(auth.api, "getSession", async () => { throw new Error("Un renouvellement ne doit pas interroger la session en base."); });
  const renewed = await POST(request({ grant: data.grant, query: "SELECT * FROM account", workspace: "demo" }));
  assert.equal(renewed.status, 200);
  assert.equal((await renewed.json()).sealedQuery.queryFingerprint, data.sealedQuery.queryFingerprint);
  const tampered = data.grant.replace(/^./, data.grant[0] === "a" ? "b" : "a");
  assert.equal((await POST(request({ grant: tampered }))).status, 401);
  assert.equal((await POST(request({ grant: "" }))).status, 401);
  assert.equal((await POST(request({ grant: 1 }))).status, 400);
  assert.throws(() => verifyRealtimeGrant(data.grant, Date.parse(identity.expiresAt)), /Reconnectez/);
  const expired = issueRealtimeGrant({ session: { id: identity.sessionId, expiresAt: new Date(0) }, user: { id: fixture.userId, email: identity.email } });
  assert.equal((await POST(request({ grant: expired }))).status, 401);
  process.env.VIGIE_ALLOWED_GOOGLE_EMAILS = "other@example.test";
  assert.equal((await POST(request({ grant: data.grant }))).status, 401);
});
